"""Chronological expected-points reconstruction from nflverse raw game states.

Published nflfastR EPA is generated by a shared retrospective EP estimator.  It
cannot establish what an estimator trained before an early evaluation season
would have predicted.  This module deliberately does not read that EPA column.

Our explicitly different EP target is the possession team's net points from a
preplay state through the end of its half (all overtime is one terminal group).
EPA measures the potential change between consecutive valid preplay states,
including actual intervening points and a sign change on possession switches.
Consequently intervening conversions/kickoffs can enter a transition: these are
not replicas of nflfastR next-score EPA.  Each season's estimator is frozen from
the preceding three supplied seasons.  The first supplied season uses EP=0 as a
declared warm-up prior.  Raw source corrections remain a retrospective-data
limitation; chronological reconstruction removes estimator-training lookahead.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import pyarrow.parquet as pq
from sklearn import __version__ as sklearn_version
from sklearn.ensemble import HistGradientBoostingRegressor
from threadpoolctl import threadpool_limits

from predictions.data import TEAM_ALIASES

EP_VERSION = "causal-remaining-half-ep-v1"
EP_FEATURE_COLUMNS = [
    "yardline_100",
    "down",
    "ydstogo",
    "half_seconds_remaining",
    "score_differential",
    "posteam_timeouts_remaining",
    "defteam_timeouts_remaining",
]
MODEL_PARAMETERS = {
    "max_iter": 60,
    "max_leaf_nodes": 15,
    "max_bins": 64,
    "l2_regularization": 10.0,
    "random_state": 42,
    "early_stopping": False,
}
RAW_COLUMNS = [
    "game_id",
    "play_id",
    "game_half",
    "qtr",
    "posteam",
    "home_team",
    "away_team",
    "total_home_score",
    "total_away_score",
    "posteam_score",
    "defteam_score",
    *[name for name in EP_FEATURE_COLUMNS if name != "score_differential"],
]


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _read_states(path: Path) -> pd.DataFrame:
    names = set(pq.read_schema(path).names)
    missing = set(RAW_COLUMNS) - names
    if missing:
        raise ValueError(f"PBP lacks raw fields for causal EP: {sorted(missing)}")
    return _prepare_states(pd.read_parquet(path, columns=RAW_COLUMNS))


def _prepare_states(raw: pd.DataFrame) -> pd.DataFrame:
    """Separate raw preplay predictors from postplay/half-terminal labels."""
    missing = set(RAW_COLUMNS) - set(raw)
    if missing:
        raise ValueError(f"Missing causal EP fields: {sorted(missing)}")
    frame = raw.copy()
    if frame[["game_id", "play_id"]].isna().any().any():
        raise ValueError("Causal EP requires nonmissing game/play IDs")
    if frame.duplicated(["game_id", "play_id"]).any():
        raise ValueError("Duplicate PBP game/play IDs in causal EP input")
    for column in ["posteam", "home_team", "away_team"]:
        frame[column] = frame[column].replace(TEAM_ALIASES)
    for column in [
        "play_id",
        "qtr",
        "total_home_score",
        "total_away_score",
        "posteam_score",
        "defteam_score",
        *[c for c in EP_FEATURE_COLUMNS if c != "score_differential"],
    ]:
        frame[column] = pd.to_numeric(frame[column], errors="raise")
    # Clock order is preferable to raw row order: review/no-play insertions may
    # have out-of-order play IDs. IDs break same-clock ties deterministically.
    frame = frame.sort_values(
        ["game_id", "qtr", "half_seconds_remaining", "play_id"],
        ascending=[True, True, False, True],
        kind="stable",
    ).reset_index(drop=True)
    home_possession = frame["posteam"].eq(frame["home_team"])
    away_possession = frame["posteam"].eq(frame["away_team"])
    frame["_home_pre"] = np.where(home_possession, frame["posteam_score"], frame["defteam_score"])
    frame["_away_pre"] = np.where(home_possession, frame["defteam_score"], frame["posteam_score"])
    # total_* are POSTPLAY, confirmed against scoring plays in nflverse data.
    group = frame.groupby(["game_id", "game_half"], dropna=False, sort=False)
    frame["_home_terminal"] = group["total_home_score"].transform("last")
    frame["_away_terminal"] = group["total_away_score"].transform("last")
    frame["score_differential"] = frame["posteam_score"] - frame["defteam_score"]
    required_finite = [
        "yardline_100",
        "down",
        "ydstogo",
        "half_seconds_remaining",
        "score_differential",
        "_home_pre",
        "_away_pre",
        "_home_terminal",
        "_away_terminal",
    ]
    finite = np.isfinite(frame[required_finite].to_numpy(dtype=float)).all(axis=1)
    frame["_valid"] = (
        finite
        & (home_possession | away_possession)
        & frame["game_half"].notna()
        & frame["down"].between(1, 4)
        & frame["yardline_100"].between(0, 100)
        & frame["ydstogo"].ge(0)
        & frame["half_seconds_remaining"].ge(0)
    )
    remaining_home = frame["_home_terminal"] - frame["_home_pre"]
    remaining_away = frame["_away_terminal"] - frame["_away_pre"]
    frame["_target"] = np.where(
        home_possession, remaining_home - remaining_away, remaining_away - remaining_home
    )
    return frame


def _epa_for_states(states: pd.DataFrame, model) -> pd.DataFrame:
    valid = states.loc[states["_valid"]].copy()
    valid["_ep"] = (
        model.predict(valid[EP_FEATURE_COLUMNS]) if model is not None and len(valid) else 0.0
    )
    group = valid.groupby(["game_id", "game_half"], sort=False)
    next_ep = group["_ep"].shift(-1).fillna(0.0)
    next_team = group["posteam"].shift(-1)
    next_home = group["_home_pre"].shift(-1).fillna(valid["_home_terminal"])
    next_away = group["_away_pre"].shift(-1).fillna(valid["_away_terminal"])
    sign = np.where(valid["posteam"].eq(valid["home_team"]), 1.0, -1.0)
    net_points = sign * ((next_home - valid["_home_pre"]) - (next_away - valid["_away_pre"]))
    possession_sign = np.where(valid["posteam"].eq(next_team), 1.0, -1.0)
    valid["epa"] = net_points + possession_sign * next_ep - valid["_ep"]
    # All source keys are present, with explicit NaN for states we cannot value.
    return states[["game_id", "play_id"]].merge(
        valid[["game_id", "play_id", "epa"]], how="left", validate="one_to_one"
    )


def reconstruct_epa(
    season_paths: dict[int, Path],
    output_dir: Path,
    *,
    games: pd.DataFrame | None = None,
) -> tuple[dict[int, Path], dict]:
    """Fit prior-season-only EP estimators and persist audited per-play EPA.

    Passing the canonical schedule additionally enforces exact result
    availability before the next season opens, and excludes incomplete games.
    No published ``epa``, probability, win-probability, or fitted nflverse model
    output enters either training or inference.
    """
    if not season_paths:
        raise ValueError("At least one PBP season is required")
    paths = {int(season): Path(path) for season, path in season_paths.items()}
    seasons = sorted(paths)
    if seasons != list(range(seasons[0], seasons[-1] + 1)):
        raise ValueError("Causal EP requires consecutive supplied seasons")
    source_hashes = {season: _sha256(path) for season, path in paths.items()}
    code_sha = _sha256(Path(__file__))
    root = Path(output_dir)
    root.mkdir(parents=True, exist_ok=True)
    schedule = None
    if games is not None:
        required = {
            "game_id",
            "season",
            "kickoff",
            "result_available_at",
            "home_score",
            "away_score",
        }
        if not required <= set(games):
            raise ValueError("Schedule lacks causal EP cutoff or completion columns")
        schedule = games.copy()
        if schedule["game_id"].duplicated().any():
            raise ValueError("Schedule has duplicate game IDs")
        for column in ["kickoff", "result_available_at"]:
            schedule[column] = pd.to_datetime(schedule[column], utc=True)
    history = {}
    outputs, records = {}, []
    for season in seasons:
        prior = [year for year in seasons if season - 3 <= year < season]
        cutoff = None
        eligible_ids = None
        train_max_available = None
        if schedule is not None:
            current = schedule.loc[schedule["season"].eq(season)]
            if current.empty:
                raise ValueError(f"No scheduled games for causal EP season {season}")
            cutoff = current["kickoff"].min()
            eligible = schedule.loc[
                schedule["season"].isin(prior)
                & schedule["result_available_at"].lt(cutoff)
                & schedule["home_score"].notna()
                & schedule["away_score"].notna()
            ]
            eligible_ids = set(eligible["game_id"])
            if len(eligible):
                train_max_available = eligible["result_available_at"].max().isoformat()
        key_data = {
            "version": EP_VERSION,
            "season": season,
            "source_code_sha256": code_sha,
            "source_hashes": {str(y): source_hashes[y] for y in [*prior, season]},
            "training_seasons": prior,
            "model_parameters": MODEL_PARAMETERS,
            "sklearn_version": sklearn_version,
            "training_game_ids_sha256": (
                hashlib.sha256("\n".join(sorted(eligible_ids)).encode()).hexdigest()
                if eligible_ids is not None
                else None
            ),
            "training_cutoff_at": cutoff.isoformat() if cutoff is not None else None,
        }
        cache_key = hashlib.sha256(json.dumps(key_data, sort_keys=True).encode()).hexdigest()
        directory = root / f"{season}-{cache_key[:20]}"
        directory.mkdir(parents=True, exist_ok=True)
        output = directory / "epa.parquet"
        metadata_path = directory / "metadata.json"
        states = _read_states(paths[season])
        history[season] = states
        if output.exists() and metadata_path.exists():
            metadata = json.loads(metadata_path.read_text())
            if metadata.get("cache_key") != cache_key or metadata.get("epa_sha256") != _sha256(
                output
            ):
                raise ValueError(
                    "Causal EP cache is corrupt; remove the affected generated directory"
                )
            outputs[season] = output
            records.append(metadata)
            # Keep only the history needed for the next prior-three-season fit.
            history = {year: frame for year, frame in history.items() if year >= season - 2}
            continue
        training = (
            pd.concat(
                [history[year].loc[history[year]["_valid"]] for year in prior],
                ignore_index=True,
            )
            if prior
            else pd.DataFrame()
        )
        if len(training) and eligible_ids is not None:
            training = training.loc[training["game_id"].isin(eligible_ids)]
        model = None
        with threadpool_limits(limits=2):
            if len(training):
                model = HistGradientBoostingRegressor(**MODEL_PARAMETERS)
                model.fit(training[EP_FEATURE_COLUMNS], training["_target"])
            epa = _epa_for_states(states, model)
        epa.to_parquet(output, index=False)
        model_path = directory / "model.joblib"
        if model is not None:
            joblib.dump(model, model_path)
        metadata = {
            **key_data,
            "cache_key": cache_key,
            "epa_sha256": _sha256(output),
            "model_sha256": _sha256(model_path) if model is not None else None,
            "training_rows": int(len(training)),
            "training_games": int(training["game_id"].nunique()) if len(training) else 0,
            "train_max_result_available_at": train_max_available,
            "feature_columns": EP_FEATURE_COLUMNS,
            "model_kind": "prior-three-seasons-hist-gradient-boosting"
            if model is not None
            else "zero-EP-warmup",
            "total_rows": len(states),
            "valued_rows": int(epa["epa"].notna().sum()),
            "definition": "Net remaining-half EP; consecutive valid-state transition EPA, including intervening special-team points; not published nflfastR EPA",
            "raw_upstream_epa_used": False,
        }
        metadata_path.write_text(json.dumps(metadata, indent=2, allow_nan=False) + "\n")
        outputs[season] = output
        records.append(metadata)
        history = {year: frame for year, frame in history.items() if year >= season - 2}
    return outputs, {
        "ep_version": EP_VERSION,
        "raw_upstream_epa_used": False,
        "source_code_sha256": code_sha,
        "models": records,
        "definition": "Chronological net remaining-half EP, distinct from nflfastR next-score EP",
        "limitation": "Raw PBP are retrospective snapshots; source corrections are not undone",
    }
